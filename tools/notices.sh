#!/bin/sh
# Print the licence text of every module linked into bin/vogter.
set -eu
export GOTOOLCHAIN=local
make build >/dev/null
echo "Third-party licences for the Go modules linked into vogter."
echo "Generated by tools/notices.sh; do not edit."
go version -m bin/vogter | awk '$1 == "dep" { print $2, $3 }' | while read -r mod ver; do
  dir=$(go list -m -f '{{.Dir}}' "$mod")
  lic=""
  for f in LICENSE LICENSE.md LICENSE.txt LICENCE COPYING; do
    if [ -f "$dir/$f" ]; then
      lic="$dir/$f"
      break
    fi
  done
  printf '\n================================================================\n%s %s\n================================================================\n\n' "$mod" "$ver"
  if [ -n "$lic" ]; then
    cat "$lic"
  else
    echo "NO LICENCE FILE FOUND" >&2
    echo "(licence file not found in module; see the upstream repository)"
  fi
done
